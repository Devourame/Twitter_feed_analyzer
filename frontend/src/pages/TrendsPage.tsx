import {
  BarChart, Bar, XAxis, YAxis, CartesianGrid, Tooltip, ResponsiveContainer, Cell,
} from 'recharts';
import { Link } from 'react-router-dom';
import { useApi } from '../hooks/useApi';
import {
  fetchTrendingHashtags, fetchHashtagEngagement, fetchTopTweets,
  fetchUserActivity, fetchSentimentEngagement, fetchHourly, fetchDaily,
} from '../api/analytics';
import ChartContainer from '../components/common/ChartContainer';
import { CHART_COLORS, DarkTooltip, SENTIMENT_FILL } from '../components/charts/chartTheme';
import { DAY_NAMES, formatCompact, formatNumber } from '../utils/format';
import styles from './pages.module.css';

const gridStyle = { stroke: CHART_COLORS.grid };
const axisTick = { fill: CHART_COLORS.axis, fontSize: 11 };

/** Horizontal ranking bar chart (category on Y). */
function RankBar({
  data, color, valueKey, nameKey, valueName,
}: {
  data: Record<string, unknown>[];
  color: string;
  valueKey: string;
  nameKey: string;
  valueName: string;
}) {
  return (
    <ResponsiveContainer width="100%" height={Math.max(220, data.length * 34 + 40)}>
      <BarChart data={data} layout="vertical" margin={{ left: 8, right: 24 }}>
        <CartesianGrid strokeDasharray="3 3" horizontal={false} {...gridStyle} />
        <XAxis type="number" tick={axisTick} tickFormatter={formatCompact} />
        <YAxis type="category" dataKey={nameKey} tick={axisTick} width={110} />
        <Tooltip content={<DarkTooltip />} cursor={{ fill: 'rgba(34,211,238,0.06)' }} />
        <Bar dataKey={valueKey} name={valueName} fill={color} radius={[0, 4, 4, 0]} />
      </BarChart>
    </ResponsiveContainer>
  );
}

export default function TrendsPage() {
  const hashtags = useApi(fetchTrendingHashtags, []);
  const hashtagEng = useApi(fetchHashtagEngagement, []);
  const topTweets = useApi(fetchTopTweets, []);
  const userActivity = useApi(fetchUserActivity, []);
  const sentimentEng = useApi(fetchSentimentEngagement, []);
  const hourly = useApi(fetchHourly, []);
  const daily = useApi(fetchDaily, []);

  const hashtagFreqData = (hashtags.data?.data ?? []).map((h) => ({
    name: `#${h.hashtag}`,
    count: h.count,
  }));

  const hashtagEngData = (hashtagEng.data?.data ?? []).map((h) => ({
    name: `#${h.hashtag}`,
    totalEngagement: h.totalEngagement,
    tweetCount: h.tweetCount,
  }));

  const userData = (userActivity.data?.data ?? []).map((u) => ({
    name: `@${u.userHandle}`,
    totalEngagement: Math.round(u.totalEngagement),
    tweetCount: u.tweetCount,
  }));

  const sentimentData = (sentimentEng.data?.data ?? []).map((s) => ({
    name: s.sentiment,
    avgEngagement: s.avgEngagement,
    totalEngagement: Math.round(s.totalEngagement),
  }));

  const hourData = (hourly.data?.data ?? []).map((p) => ({
    hour: `${String(p.hour).padStart(2, '0')}:00`,
    tweets: p.tweetCount,
  }));

  const dayData = (daily.data?.data ?? [])
    .slice()
    .sort((a, b) => a.dayOfWeek - b.dayOfWeek)
    .map((p) => ({ day: DAY_NAMES[p.dayOfWeek - 1] ?? `Day ${p.dayOfWeek}`, tweets: p.tweetCount }));

  return (
    <div>
      <header className={styles.headerRow}>
        <div>
          <h1 className={styles.pageTitle}>Trends &amp; Engagement</h1>
          <p className={styles.pageDescription}>
            Rankings and comparisons. Engagement score = likes + 2×retweets +
            1.5×replies (project-defined metric, not an official Twitter score).
          </p>
        </div>
      </header>

      <div className={`${styles.grid} ${styles.cardGrid2}`}>
        <ChartContainer
          title="Top hashtags by frequency"
          subtitle="Click a bar's label to open the filtered tweet list"
          loading={hashtags.loading}
          error={hashtags.error}
          onRetry={hashtags.refresh}
          isEmpty={hashtagFreqData.length === 0}
        >
          <RankBar data={hashtagFreqData} color={CHART_COLORS.primary} valueKey="count" nameKey="name" valueName="Tweets" />
          <div className={styles.rankList} style={{ marginTop: 12 }}>
            {(hashtags.data?.data ?? []).slice(0, 5).map((h) => (
              <Link key={h.hashtag} className={styles.rankRow} style={{ textDecoration: 'none' }} to={`/tweets?hashtag=${h.hashtag}`}>
                <span className={styles.rankMain}>#{h.hashtag}</span>
                <span className={styles.rankValue}>{formatCompact(h.count)} tweets</span>
              </Link>
            ))}
          </div>
        </ChartContainer>

        <ChartContainer
          title="Hashtag engagement"
          subtitle="Total engagement generated by tweets per hashtag"
          loading={hashtagEng.loading}
          error={hashtagEng.error}
          onRetry={hashtagEng.refresh}
          isEmpty={hashtagEngData.length === 0}
        >
          <RankBar data={hashtagEngData} color={CHART_COLORS.primary} valueKey="totalEngagement" nameKey="name" valueName="Engagement" />
        </ChartContainer>

        <ChartContainer
          title="User engagement rankings"
          subtitle="Top 10 users by total engagement their tweets generated"
          loading={userActivity.loading}
          error={userActivity.error}
          onRetry={userActivity.refresh}
          isEmpty={userData.length === 0}
        >
          <RankBar data={userData} color={CHART_COLORS.primary} valueKey="totalEngagement" nameKey="name" valueName="Engagement" />
          <div className={styles.rankList} style={{ marginTop: 12 }}>
            {(userActivity.data?.data ?? []).slice(0, 5).map((u) => (
              <Link key={u.userHandle} className={styles.rankRow} style={{ textDecoration: 'none' }} to={`/users?handle=${u.userHandle}`}>
                <span className={styles.rankMain}>@{u.userHandle}</span>
                <span className={styles.rankSub}>{u.tweetCount} tweets</span>
                <span className={styles.rankValue}>{formatCompact(Math.round(u.totalEngagement))}</span>
              </Link>
            ))}
          </div>
        </ChartContainer>

        <ChartContainer
          title="Engagement by sentiment"
          subtitle="Average engagement score per sentiment group"
          loading={sentimentEng.loading}
          error={sentimentEng.error}
          onRetry={sentimentEng.refresh}
          isEmpty={sentimentData.length === 0}
        >
          <ResponsiveContainer width="100%" height={240}>
            <BarChart data={sentimentData}>
              <CartesianGrid strokeDasharray="3 3" {...gridStyle} />
              <XAxis dataKey="name" tick={axisTick} />
              <YAxis tick={axisTick} tickFormatter={formatCompact} />
              <Tooltip content={<DarkTooltip />} cursor={{ fill: 'rgba(34,211,238,0.06)' }} />
              <Bar dataKey="avgEngagement" name="Avg engagement" radius={[4, 4, 0, 0]}>
                {sentimentData.map((s) => (
                  <Cell key={s.name} fill={SENTIMENT_FILL(s.name)} />
                ))}
              </Bar>
            </BarChart>
          </ResponsiveContainer>
        </ChartContainer>

        <ChartContainer
          title="Top tweets by engagement"
          subtitle="Highest-scoring tweets in the dataset"
          loading={topTweets.loading}
          error={topTweets.error}
          onRetry={topTweets.refresh}
          isEmpty={(topTweets.data?.data?.length ?? 0) === 0}
        >
          <ol className={styles.rankList}>
            {(topTweets.data?.data ?? []).slice(0, 10).map((t, i) => (
              <li key={t.tweetId} className={styles.rankRow}>
                <span className={styles.rankIndex}>{i + 1}</span>
                <Link className={styles.rankMain} to={`/tweets?handle=${t.userHandle}`} title={t.text}>
                  @{t.userHandle}: {t.text}
                </Link>
                <span className={styles.rankValue}>{formatNumber(Math.round(t.engagementScore))}</span>
              </li>
            ))}
          </ol>
        </ChartContainer>

        <ChartContainer
          title="Hourly activity"
          subtitle="Tweet volume by hour of day"
          loading={hourly.loading}
          error={hourly.error}
          onRetry={hourly.refresh}
          isEmpty={hourData.length === 0}
        >
          <ResponsiveContainer width="100%" height={240}>
            <BarChart data={hourData}>
              <CartesianGrid strokeDasharray="3 3" {...gridStyle} />
              <XAxis dataKey="hour" tick={{ fill: CHART_COLORS.axis, fontSize: 10 }} interval={2} />
              <YAxis tick={axisTick} tickFormatter={formatCompact} />
              <Tooltip content={<DarkTooltip />} cursor={{ fill: 'rgba(34,211,238,0.06)' }} />
              <Bar dataKey="tweets" name="Tweets" fill={CHART_COLORS.primary} radius={[3, 3, 0, 0]} />
            </BarChart>
          </ResponsiveContainer>
        </ChartContainer>

        <ChartContainer
          title="Daily activity"
          subtitle="Tweet volume by day of week"
          loading={daily.loading}
          error={daily.error}
          onRetry={daily.refresh}
          isEmpty={dayData.length === 0}
        >
          <ResponsiveContainer width="100%" height={240}>
            <BarChart data={dayData}>
              <CartesianGrid strokeDasharray="3 3" {...gridStyle} />
              <XAxis dataKey="day" tick={axisTick} />
              <YAxis tick={axisTick} tickFormatter={formatCompact} />
              <Tooltip content={<DarkTooltip />} cursor={{ fill: 'rgba(34,211,238,0.06)' }} />
              <Bar dataKey="tweets" name="Tweets" fill={CHART_COLORS.primary} radius={[3, 3, 0, 0]} />
            </BarChart>
          </ResponsiveContainer>
        </ChartContainer>
      </div>
    </div>
  );
}
